  function setText(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n",
        key
      );
    }
  }

  function setPlaceholder(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n-placeholder",
        key
      );
    }
  }

  function setMany(selector, keys) {
    document
      .querySelectorAll(selector)
      .forEach((element, index) => {
        if (keys[index]) {
          element.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function createTextSpan(
    parent,
    className,
    translationKey
  ) {
    if (!parent) {
      return;
    }

    let span =
      parent.querySelector(
        "." + className
      );

    if (!span) {
      span =
        document.createElement("span");

      span.className =
        className;

      Array.from(
        parent.childNodes
      ).forEach((node) => {
        if (
          node.nodeType ===
          Node.TEXT_NODE
        ) {
          node.remove();
        }
      });

      parent.appendChild(span);
    }

    span.setAttribute(
      "data-i18n",
      translationKey
    );
  }

