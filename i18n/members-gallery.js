  function updatePageTitle() {
    const language =
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage
        .getCurrentLanguage ===
        "function"
        ? window.PetsDogueLanguage
            .getCurrentLanguage()
        : { code: "en" };

    const dictionary =
      window.PetsDogueTranslations
        .membersGallery[
          language.code
        ] ||
      window.PetsDogueTranslations
        .membersGallery.en;

    if (
      dictionary &&
      dictionary.meta &&
      dictionary.meta.title
    ) {
      document.title =
        dictionary.meta.title;
    }
  }

  window.addEventListener(
    "petsdogue:languagechange",
    function () {
      window.setTimeout(
        updatePageTitle,
        0
      );
    }
  );

