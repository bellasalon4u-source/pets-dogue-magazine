  /* =========================================================
     SCHEDULING
  ========================================================= */

  let scheduled = false;


  function scheduleTranslate() {

    if (scheduled) return;


    scheduled = true;


    requestAnimationFrame(() => {

      scheduled = false;

      translateStatic();

    });
  }


  /* =========================================================
     START
  ========================================================= */

  if (
    document.readyState ===
    "loading"
  ) {

    document.addEventListener(
      "DOMContentLoaded",
      scheduleTranslate,
      { once: true }
    );

  } else {

    scheduleTranslate();
  }


  /* =========================================================
     LANGUAGE CHANGE
  ========================================================= */

  const htmlObserver =
    new MutationObserver(
      mutations => {

        const changed =
          mutations.some(
            mutation =>
              mutation.type ===
              "attributes"
          );


        if (changed) {
          scheduleTranslate();
        }

      }
    );


  htmlObserver.observe(
    document.documentElement,
    {
      attributes: true,
      attributeFilter: [
        "lang",
        "dir"
      ]
    }
  );


  /* =========================================================
     DYNAMIC MODALS / LISTINGS
     Translate only newly inserted content.
     No endless body re-render loop.
  ========================================================= */

  function startBodyObserver() {

    if (!document.body) return;


    const observer =
      new MutationObserver(
        mutations => {

          mutations.forEach(
            mutation => {

              mutation.addedNodes
                .forEach(node => {

                  if (
                    node.nodeType !==
                    Node.ELEMENT_NODE
                  ) {
                    return;
                  }


                  requestAnimationFrame(
                    () => {

                      translateDynamicText(
                        node
                      );

                      const {
                        ui,
                        page
                      } = getPack();


                      translateListingCards(
                        ui,
                        page,
                        node
                      );

                      translateSearchMessages(
                        ui,
                        node
                      );

                    }
                  );

                });

            });

        }
      );


    observer.observe(
      document.body,
      {
        childList: true,
        subtree: true
      }
    );
  }


  if (document.body) {

    startBodyObserver();

  } else {

    document.addEventListener(
      "DOMContentLoaded",
      startBodyObserver,
      { once: true }
    );
  }


  /* =========================================================
     SAME-TAB LANGUAGE SWITCH
  ========================================================= */

  document.addEventListener(
    "change",
    event => {

      if (
        event.target &&
        event.target.id ===
        "languageSelect"
      ) {

        setTimeout(
          scheduleTranslate,
          0
        );

        setTimeout(
          scheduleTranslate,
          80
        );
      }

    }
  );


  window.addEventListener(
    "storage",
    scheduleTranslate
  );


  /* =========================================================
     PUBLIC HOOK
  ========================================================= */

  window.PetsDogueMarketplaceApplyLanguage =
    scheduleTranslate;

