  function normalizeLanguage(value) {

    let lang = String(value || "")
      .trim()
      .toLowerCase()
      .replace(/_/g, "-");

    if (NORMALIZE[lang]) {
      lang = NORMALIZE[lang];
    }

    if (MARKET[lang]) {
      return lang;
    }

    const short = lang.split("-")[0];

    if (NORMALIZE[short]) {
      return NORMALIZE[short];
    }

    if (MARKET[short]) {
      return short;
    }

    return "en";
  }


  function getLanguage() {

    if (
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage.getCurrentLanguage === "function"
    ) {

      try {

        const current =
          window.PetsDogueLanguage.getCurrentLanguage();

        if (typeof current === "string") {
          return normalizeLanguage(current);
        }

        if (current && current.code) {
          return normalizeLanguage(current.code);
        }

      } catch (e) {}

    }


    const htmlLang =
      document.documentElement.getAttribute("lang");

    if (htmlLang) {

      const normalized =
        normalizeLanguage(htmlLang);

      if (
        normalized !== "en" ||
        String(htmlLang).toLowerCase().startsWith("en")
      ) {
        return normalized;
      }

    }


    const keys = [
      "pets_dogue_language",
      "petsDogueLanguage",
      "dogue_language",
      "selectedLanguage",
      "language",
      "lang"
    ];


    for (const key of keys) {

      const value =
        localStorage.getItem(key);

      if (value) {
        return normalizeLanguage(value);
      }

    }


    return "en";
  }


