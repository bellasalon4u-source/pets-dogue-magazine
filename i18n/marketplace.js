  function replaceExactText(root, replacements) {

    if (!root) return;

    const walker =
      document.createTreeWalker(
        root,
        NodeFilter.SHOW_TEXT
      );

    const nodes = [];

    while (walker.nextNode()) {
      nodes.push(walker.currentNode);
    }


    nodes.forEach(node => {

      const raw =
        node.nodeValue;

      if (!raw || !raw.trim()) return;

      const trimmed =
        raw.trim();

      if (
        Object.prototype.hasOwnProperty.call(
          replacements,
          trimmed
        )
      ) {

        const leading =
          raw.match(/^\s*/)?.[0] || "";

        const trailing =
          raw.match(/\s*$/)?.[0] || "";

        node.nodeValue =
          leading +
          replacements[trimmed] +
          trailing;
      }

    });
  }


  function replaceAgeAndGender(root, ui) {

    if (!root) return;

    const walker =
      document.createTreeWalker(
        root,
        NodeFilter.SHOW_TEXT
      );

    const nodes = [];

    while (walker.nextNode()) {
      nodes.push(walker.currentNode);
    }


    nodes.forEach(node => {

      let text =
        node.nodeValue;

      if (!text) return;


      text =
        text.replace(
          /\bFemale\b/g,
          ui.female
        );

      text =
        text.replace(
          /\bMale\b/g,
          ui.male
        );


      text =
        text.replace(
          /\b1 year\b/g,
          "1 " + ui.year
        );


      text =
        text.replace(
          /\b(\d+)\s+years\b/g,
          function (_, number) {
            return number + " " + ui.years;
          }
        );


      if (node.nodeValue !== text) {
        node.nodeValue = text;
      }

    });
  }


