(function () {
  "use strict";

  function setText(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n",
        key
      );
    }
  }

  function setMany(selector, keys) {
    document
      .querySelectorAll(selector)
      .forEach((element, index) => {
        if (keys[index]) {
          element.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function setPlaceholder(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n-placeholder",
        key
      );
    }
  }

  function getLanguageCode() {
    if (
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage
        .getCurrentLanguage === "function"
    ) {
      return window.PetsDogueLanguage
        .getCurrentLanguage().code;
    }

    return (
      new URLSearchParams(
        window.location.search
      ).get("lang") ||
      localStorage.getItem(
        "pets_dogue_language"
      ) ||
      "en"
    );
  }

  function getDictionary() {
    const language =
      getLanguageCode();

    return (
      window.PetsDogueTranslations.account[
        language
      ] ||
      window.PetsDogueTranslations.account.en
    );
  }

  function translateStatus(status) {
    const dictionary =
      getDictionary();

    if (status === "Club Monthly") {
      return dictionary.profile.clubMonthly;
    }

    if (status === "Club Yearly") {
      return dictionary.profile.clubYearly;
    }

    return dictionary.profile.freeReader;
  }

  function getSavedProfile() {
    const saved =
      localStorage.getItem("pd_profile");

    if (!saved) {
      return null;
    }

    try {
      return JSON.parse(saved);
    } catch (error) {
      console.error(
        "Could not read PETS & DOGUE profile.",
        error
      );

      return null;
    }
  }

  function prepareStaticPage() {
    setText(
      ".hero h1",
      "account.hero.title"
    );

    setText(
      ".hero p",
      "account.hero.description"
    );

    const stats =
      document.querySelectorAll(".stat");

    const statKeys = [
      "account.profile.hearts",
      "account.profile.posts",
      "account.profile.pets",
      "account.profile.listings"
    ];

    stats.forEach((stat, index) => {
      const key = statKeys[index];

      if (!key) return;

      Array.from(
        stat.childNodes
      ).forEach((node) => {
        if (
          node.nodeType === Node.TEXT_NODE &&
          node.textContent.trim()
        ) {
          const label =
            document.createElement("span");

          label.setAttribute(
            "data-i18n",
            key
          );

          node.replaceWith(label);
        }
      });
    });

    setText(
      ".member-card h2",
      "account.memberCard.title"
    );

    const cardParagraphs =
      document.querySelectorAll(
        ".member-card p"
      );

    if (cardParagraphs[3]) {
      cardParagraphs[3].setAttribute(
        "data-i18n",
        "account.memberCard.access"
      );
    }

    const panels =
      document.querySelectorAll(
        ".panel"
      );

    if (panels[0]) {
      const title =
        panels[0].querySelector("h2");

      if (title) {
        title.setAttribute(
          "data-i18n",
          "account.account.title"
        );
      }
    }

    if (panels[1]) {
      const title =
        panels[1].querySelector("h2");

      if (title) {
        title.setAttribute(
          "data-i18n",
          "account.pets.title"
        );
      }
    }

    if (panels[2]) {
      const title =
        panels[2].querySelector("h2");

      if (title) {
        title.setAttribute(
          "data-i18n",
          "account.quick.title"
        );
      }
    }

    setPlaceholder(
      "#userName",
      "account.account.namePlaceholder"
    );

    setPlaceholder(
      "#petName",
      "account.account.petPlaceholder"
    );

    setPlaceholder(
      "#newPetName",
      "account.pets.namePlaceholder"
    );

    setPlaceholder(
      "#newBreed",
      "account.pets.breedPlaceholder"
    );

    setPlaceholder(
      "#newStory",
      "account.pets.storyPlaceholder"
    );

    const membershipOptions =
      document.querySelectorAll(
        "#membership option"
      );

    const optionValues = [
      "Free Reader",
      "Club Monthly",
      "Club Yearly"
    ];

    const optionKeys = [
      "account.profile.freeReader",
      "account.profile.clubMonthly",
      "account.profile.clubYearly"
    ];

    membershipOptions.forEach(
      (option, index) => {
        if (optionValues[index]) {
          option.value =
            optionValues[index];
        }

        if (optionKeys[index]) {
          option.setAttribute(
            "data-i18n",
            optionKeys[index]
          );
        }
      }
    );

    const accountButtons =
      panels[0]
        ? panels[0].querySelectorAll(
            "button"
          )
        : [];

    const accountButtonKeys = [
      "account.account.save",
      "account.account.load",
      "account.account.logout"
    ];

    accountButtons.forEach(
      (button, index) => {
        if (accountButtonKeys[index]) {
          button.setAttribute(
            "data-i18n",
            accountButtonKeys[index]
          );
        }
      }
    );

    setText(
      ".panel:nth-child(2) button",
      "account.pets.add"
    );

    const defaultPet =
      document.querySelector(
        "#petList .pet-card"
      );

    if (defaultPet) {
      const title =
        defaultPet.querySelector("h3");

      const descriptions =
        defaultPet.querySelectorAll("p");

      if (title) {
        title.setAttribute(
          "data-i18n",
          "account.pets.defaultName"
        );
      }

      if (descriptions[0]) {
        descriptions[0].setAttribute(
          "data-i18n",
          "account.pets.defaultBreed"
        );
      }

      if (descriptions[1]) {
        descriptions[1].setAttribute(
          "data-i18n",
          "account.pets.defaultStory"
        );
      }
    }

    setMany(
      ".quick-link",
      [
        "account.quick.gallery",
        "account.quick.marketplace",
        "account.quick.club",
        "account.quick.community",
        "account.quick.contests",
        "account.quick.wellness"
      ]
    );

    setText(
      "footer p",
      "common.footer.subtitle"
    );

    setMany(
      ".footer-links a",
      [
        "account.footer.home",
        "account.footer.club",
        "account.footer.gallery",
        "account.footer.marketplace",
        "account.footer.privacy",
        "account.footer.contact"
      ]
    );

    setText(
      ".admin-small",
      "account.footer.admin"
    );
  }

  function translateMemberCard() {
    const dictionary =
      getDictionary();

    const data =
      getSavedProfile();

    const name =
      data && data.name
        ? data.name
        : dictionary.profile.guest;

    const status =
      data && data.status
        ? data.status
        : "Free Reader";

    const cardParagraphs =
      document.querySelectorAll(
        ".member-card p"
      );

    if (cardParagraphs[0]) {
      cardParagraphs[0].innerHTML =
        `<strong>${dictionary.memberCard.name}</strong> <span id="cardName"></span>`;

      const cardName =
        cardParagraphs[0].querySelector(
          "#cardName"
        );

      if (cardName) {
        cardName.textContent = name;
      }
    }

    if (cardParagraphs[1]) {
      cardParagraphs[1].innerHTML =
        `<strong>${dictionary.memberCard.status}</strong> <span id="cardStatus"></span>`;

      const cardStatus =
        cardParagraphs[1].querySelector(
          "#cardStatus"
        );

      if (cardStatus) {
        cardStatus.textContent =
          translateStatus(status);
      }
    }

    if (cardParagraphs[2]) {
      cardParagraphs[2].innerHTML =
        `<strong>${dictionary.memberCard.memberId}</strong> PD-000001`;
    }
  }

  function translateProfileDisplay() {
    const dictionary =
      getDictionary();

    const data =
      getSavedProfile();

    const name =
      data && data.name
        ? data.name
        : dictionary.profile.guest;

    const status =
      data && data.status
        ? data.status
        : "Free Reader";

    const profileName =
      document.getElementById(
        "profileName"
      );

    const memberStatus =
      document.getElementById(
        "memberStatus"
      );

    if (profileName) {
      profileName.textContent = name;
    }

    if (memberStatus) {
      memberStatus.textContent =
        translateStatus(status);
    }

    translateMemberCard();
  }

  function updateTitle() {
    document.title =
      getDictionary().meta.title;
  }

  window.saveProfile =
    function () {
      const dictionary =
        getDictionary();

      const nameInput =
        document.getElementById(
          "userName"
        );

      const petInput =
        document.getElementById(
          "petName"
        );

      const membership =
        document.getElementById(
          "membership"
        );

      const avatar =
        document.getElementById(
          "avatar"
        );

      const data = {
        name: nameInput
          ? nameInput.value.trim()
          : "",

        pet: petInput
          ? petInput.value.trim()
          : "",

        status: membership
          ? membership.value
          : "Free Reader",

        avatar: avatar
          ? avatar.src
          : ""
      };

      localStorage.setItem(
        "pd_profile",
        JSON.stringify(data)
      );

      translateProfileDisplay();

      alert(
        dictionary.account.saved
      );
    };

  window.loadProfile =
    function () {
      const data =
        getSavedProfile();

      if (!data) {
        translateProfileDisplay();
        return;
      }

      const userName =
        document.getElementById(
          "userName"
        );

      const petName =
        document.getElementById(
          "petName"
        );

      const membership =
        document.getElementById(
          "membership"
        );

      const avatar =
        document.getElementById(
          "avatar"
        );

      if (userName) {
        userName.value =
          data.name || "";
      }

      if (petName) {
        petName.value =
          data.pet || "";
      }

      if (membership) {
        membership.value =
          data.status ||
          "Free Reader";
      }

      if (
        avatar &&
        data.avatar
      ) {
        avatar.src =
          data.avatar;
      }

      translateProfileDisplay();
    };

  window.logout =
    function () {
      localStorage.removeItem(
        "pd_profile"
      );

      window.location.reload();
    };

  window.addPet =
    function () {
      const nameInput =
        document.getElementById(
          "newPetName"
        );

      const breedInput =
        document.getElementById(
          "newBreed"
        );

      const storyInput =
        document.getElementById(
          "newStory"
        );

      if (!nameInput) return;

      const name =
        nameInput.value.trim();

      const breed =
        breedInput
          ? breedInput.value.trim()
          : "";

      const story =
        storyInput
          ? storyInput.value.trim()
          : "";

      if (!name) return;

      const card =
        document.createElement("div");

      card.className = "pet-card";

      const heading =
        document.createElement("h3");

      const breedText =
        document.createElement("p");

      const storyText =
        document.createElement("p");

      heading.textContent = name;
      breedText.textContent = breed;
      storyText.textContent = story;

      card.appendChild(heading);
      card.appendChild(breedText);
      card.appendChild(storyText);

      const petList =
        document.getElementById(
          "petList"
        );

      if (petList) {
        petList.appendChild(card);
      }

      const petsValue =
        document.getElementById(
          "petsValue"
        );

      if (petsValue) {
        petsValue.textContent =
          Number(
            petsValue.textContent
          ) + 1;
      }

      nameInput.value = "";

      if (breedInput) {
        breedInput.value = "";
      }

      if (storyInput) {
        storyInput.value = "";
      }
    };

  function preparePage() {
    prepareStaticPage();
    window.loadProfile();
    translateMemberCard();
    updateTitle();
  }

  window.addEventListener(
    "petsdogue:languagechange",
    function () {
      window.setTimeout(
        function () {
          translateProfileDisplay();
          updateTitle();
        },
        0
      );
    }
  );

  if (
    document.readyState ===
    "loading"
  ) {
    document.addEventListener(
      "DOMContentLoaded",
      preparePage,
      {
        once: true
      }
    );
  } else {
    preparePage();
  }
})();
