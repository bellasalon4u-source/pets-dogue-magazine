(function () {
  "use strict";

  function setText(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n",
        key
      );
    }
  }

  function setMany(selector, keys) {
    document
      .querySelectorAll(selector)
      .forEach(function (element, index) {
        if (keys[index]) {
          element.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function getLanguageCode() {
    if (
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage
        .getCurrentLanguage === "function"
    ) {
      return window.PetsDogueLanguage
        .getCurrentLanguage().code;
    }

    return (
      new URLSearchParams(
        window.location.search
      ).get("lang") ||
      localStorage.getItem(
        "pets_dogue_language"
      ) ||
      "en"
    );
  }

  function getDictionary() {
    const language =
      getLanguageCode();

    return (
      window.PetsDogueTranslations
        .copyright[language] ||
      window.PetsDogueTranslations
        .copyright.en
    );
  }

  function prepareNavigation() {
    setMany(
      "header nav a",
      [
        "copyright.navigation.home",
        "copyright.navigation.latestIssue",
        "copyright.navigation.archive",
        "copyright.navigation.articles",
        "copyright.navigation.categories",
        "copyright.navigation.about",
        "copyright.navigation.advertise",
        "copyright.navigation.contact"
      ]
    );
  }

  function preparePolicy() {
    setText(
      ".policy h1",
      "copyright.policy.title"
    );

    const paragraphs =
      document.querySelectorAll(
        ".policy > p"
      );

    const paragraphKeys = [
      "copyright.policy.introduction",
      "copyright.policy.ownershipText",
      "copyright.policy.imagesText",
      "copyright.policy.confirmationText",
      "copyright.policy.reuseText",
      "copyright.policy.complaintsText",
      "copyright.policy.removalText"
    ];

    paragraphs.forEach(function (
      paragraph,
      index
    ) {
      if (paragraphKeys[index]) {
        paragraph.setAttribute(
          "data-i18n",
          paragraphKeys[index]
        );
      }
    });

    const headings =
      document.querySelectorAll(
        ".policy h2"
      );

    const headingKeys = [
      "copyright.policy.ownershipTitle",
      "copyright.policy.imagesTitle",
      "copyright.policy.reuseTitle",
      "copyright.policy.complaintsTitle",
      "copyright.policy.removalTitle",
      "copyright.policy.contactTitle"
    ];

    headings.forEach(function (
      heading,
      index
    ) {
      if (headingKeys[index]) {
        heading.setAttribute(
          "data-i18n",
          headingKeys[index]
        );
      }
    });

    const lists =
      document.querySelectorAll(
        ".policy ul"
      );

    if (lists[0]) {
      setListKeys(
        lists[0],
        [
          "copyright.policy.imageOne",
          "copyright.policy.imageTwo",
          "copyright.policy.imageThree"
        ]
      );
    }

    if (lists[1]) {
      setListKeys(
        lists[1],
        [
          "copyright.policy.complaintOne",
          "copyright.policy.complaintTwo",
          "copyright.policy.complaintThree",
          "copyright.policy.complaintFour"
        ]
      );
    }
  }

  function setListKeys(list, keys) {
    list
      .querySelectorAll("li")
      .forEach(function (item, index) {
        if (keys[index]) {
          item.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function translateContact() {
    const dictionary =
      getDictionary();

    const paragraphs =
      document.querySelectorAll(
        ".policy > p"
      );

    const contactParagraph =
      paragraphs[7];

    if (contactParagraph) {
      contactParagraph.innerHTML =
        dictionary.policy.contactText +
        "<br><br>" +
        '<a href="mailto:petsanddogue@gmail.com">' +
        "petsanddogue@gmail.com" +
        "</a>";
    }
  }

  function prepareFooter() {
    setText(
      "footer > p",
      "common.footer.subtitle"
    );

    setMany(
      ".footer-links a",
      [
        "copyright.footer.privacy",
        "copyright.footer.terms",
        "copyright.footer.copyright",
        "copyright.footer.cookies",
        "copyright.footer.contact",
        "copyright.footer.advertise"
      ]
    );

    setText(
      ".admin-small",
      "copyright.footer.admin"
    );
  }

  function updateMetadata() {
    document.title =
      getDictionary().meta.title;

    document.documentElement.lang =
      getLanguageCode();
  }

  function preparePage() {
    prepareNavigation();
    preparePolicy();
    prepareFooter();
    translateContact();
    updateMetadata();
  }

  window.addEventListener(
    "petsdogue:languagechange",
    function () {
      window.setTimeout(
        function () {
          translateContact();
          updateMetadata();
        },
        0
      );
    }
  );

  if (
    document.readyState === "loading"
  ) {
    document.addEventListener(
      "DOMContentLoaded",
      preparePage,
      {
        once: true
      }
    );
  } else {
    preparePage();
  }
})();
