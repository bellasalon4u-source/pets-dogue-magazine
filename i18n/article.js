  function updateMetadata() {
    const dictionary =
      getDictionary();

    document.title =
      dictionary.meta.title;

    const description =
      document.querySelector(
        'meta[name="description"]'
      );

    if (description) {
      description.setAttribute(
        "content",
        dictionary.meta.description
      );
    }
  }

  function updateDocumentLanguage() {
    const languages = {
      en: "en",
      uk: "uk",
      ru: "ru",
      es: "es"
    };

    document.documentElement.lang =
      languages[getLanguageCode()] ||
      "en";
  }

  window.toggleSpeech =
    function () {
      const dictionary =
        getDictionary();

      const button =
        document.getElementById(
          "listenButton"
        );

      if (
        !(
          "speechSynthesis" in
          window
        )
      ) {
        alert(
          dictionary.toolbar
            .unsupported
        );

        return;
      }

      if (window.speechActive) {
        window.speechSynthesis
          .cancel();

        window.speechActive =
          false;

        if (button) {
          button.classList.remove(
            "active"
          );

          button.textContent =
            dictionary.toolbar.listen;
        }

        return;
      }

      const utterance =
        new SpeechSynthesisUtterance(
          window.getArticleSpeechText()
        );

      utterance.rate = 0.95;
      utterance.pitch = 1;
      utterance.lang =
        document.documentElement
          .lang || "en";

      utterance.onend =
        utterance.onerror =
          function () {
            window.speechActive =
              false;

            if (button) {
              button.classList.remove(
                "active"
              );

              button.textContent =
                getDictionary()
                  .toolbar.listen;
            }
          };

      window.speechUtterance =
        utterance;

      window.speechSynthesis.cancel();
      window.speechSynthesis.speak(
        utterance
      );

      window.speechActive = true;

      if (button) {
        button.classList.add(
          "active"
        );

        button.textContent =
          dictionary.toolbar.stop;
      }
    };

  window.copyArticleLink =
    function () {
      const dictionary =
        getDictionary();

      if (
        navigator.clipboard &&
        navigator.clipboard.writeText
      ) {
        navigator.clipboard
          .writeText(
            window.location.href
          )
          .then(function () {
            alert(
              dictionary.toolbar
                .copied
            );
          })
          .catch(function () {
            alert(
              dictionary.toolbar
                .copyFallback +
                window.location.href
            );
          });

        return;
      }

      alert(
        dictionary.toolbar
          .copyFallback +
          window.location.href
      );
    };

