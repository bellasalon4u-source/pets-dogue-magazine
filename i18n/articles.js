  function updateResultsText() {
    const element =
      document.getElementById(
        "resultsText"
      );

    if (!element) {
      return;
    }

    const cards =
      Array.from(
        document.querySelectorAll(
          ".article-card"
        )
      );

    const count =
      cards.filter(
        (card) => {
          return (
            card.style.display !==
              "none" &&
            !card.hidden
          );
        }
      ).length;

    const translations =
      getTranslations();

    if (!translations.results) {
      return;
    }

    if (count === 1) {
      element.textContent =
        translations.results.one;

      return;
    }

    element.textContent =
      translations.results.many
        .replace(
          "{count}",
          String(count)
        );
  }

  function updateCardMeta() {
    const translations =
      getTranslations();

    if (
      !translations.cardMeta
    ) {
      return;
    }

    document
      .querySelectorAll(
        ".article-card"
      )
      .forEach(
        (card, index) => {
          const meta =
            card.querySelector(
              ".article-meta"
            );

          const roleKey =
            CARD_META_KEYS[index];

          const minutes =
            CARD_MINUTES[index];

          if (
            !meta ||
            !roleKey ||
            !minutes
          ) {
            return;
          }

          const role =
            translations.cardMeta[
              roleKey
            ];

          const time =
            translations
              .cardMeta
              .minute
              .replace(
                "{count}",
                String(minutes)
              );

          meta.textContent =
            `${role} • ${time}`;
        }
      );
  }

  function updateMetadata() {
    const translations =
      getTranslations();

    const common =
      window
        .PetsDogueTranslations
        .common || {};

    const code =
      getLanguageCode();

    const commonLanguage =
      common[code] ||
      common.en;

    if (
      commonLanguage &&
      commonLanguage.navigation &&
      commonLanguage
        .navigation
        .articles
    ) {
      document.title =
        `${commonLanguage.navigation.articles} | PETS & DOGUE`;
    } else {
      document.title =
        "Articles | PETS & DOGUE";
    }

    const description =
      document.querySelector(
        'meta[name="description"]'
      );

    if (
      description &&
      translations.hero &&
      translations
        .hero
        .description
    ) {
      description.setAttribute(
        "content",
        translations
          .hero
          .description
      );
    }
  }

  function applyDynamicText() {
    updateResultsText();
    updateCardMeta();
    updateMetadata();
  }

  function wrapArticleFilter() {
    const original =
      window.filterArticles;

    if (
      typeof original !==
        "function" ||
      original
        .__petsDogueWrapped
    ) {
      return;
    }

    function wrappedFilter() {
      const result =
        original.apply(
          this,
          arguments
        );

      updateResultsText();

      return result;
    }

    wrappedFilter
      .__petsDogueWrapped =
      true;

    window.filterArticles =
      wrappedFilter;
  }

