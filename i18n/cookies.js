(function () {
  "use strict";

  function setText(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n",
        key
      );
    }
  }

  function setMany(selector, keys) {
    document
      .querySelectorAll(selector)
      .forEach(function (element, index) {
        if (keys[index]) {
          element.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function getLanguageCode() {
    if (
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage
        .getCurrentLanguage === "function"
    ) {
      return window.PetsDogueLanguage
        .getCurrentLanguage().code;
    }

    return (
      new URLSearchParams(
        window.location.search
      ).get("lang") ||
      localStorage.getItem(
        "pets_dogue_language"
      ) ||
      "en"
    );
  }

  function getDictionary() {
    const language =
      getLanguageCode();

    return (
      window.PetsDogueTranslations
        .cookies[language] ||
      window.PetsDogueTranslations
        .cookies.en
    );
  }

  function prepareNavigation() {
    setMany(
      "header nav a",
      [
        "cookies.navigation.home",
        "cookies.navigation.latestIssue",
        "cookies.navigation.archive",
        "cookies.navigation.articles",
        "cookies.navigation.categories",
        "cookies.navigation.about",
        "cookies.navigation.advertise",
        "cookies.navigation.contact"
      ]
    );
  }

  function preparePolicy() {
    setText(
      ".policy h1",
      "cookies.policy.title"
    );

    const headings =
      document.querySelectorAll(
        ".policy h2"
      );

    const headingKeys = [
      "cookies.policy.whatTitle",
      "cookies.policy.useTitle",
      "cookies.policy.thirdPartyTitle",
      "cookies.policy.managingTitle",
      "cookies.policy.updatesTitle",
      "cookies.policy.contactTitle"
    ];

    headings.forEach(function (
      heading,
      index
    ) {
      if (headingKeys[index]) {
        heading.setAttribute(
          "data-i18n",
          headingKeys[index]
        );
      }
    });

    const paragraphs =
      document.querySelectorAll(
        ".policy > p"
      );

    const paragraphKeys = [
      "cookies.policy.introduction",
      "cookies.policy.whatText",
      "cookies.policy.thirdPartyText",
      "cookies.policy.managingText",
      "cookies.policy.updatesText"
    ];

    paragraphs.forEach(function (
      paragraph,
      index
    ) {
      if (paragraphKeys[index]) {
        paragraph.setAttribute(
          "data-i18n",
          paragraphKeys[index]
        );
      }
    });

    const items =
      document.querySelectorAll(
        ".policy li"
      );

    const itemKeys = [
      "cookies.policy.useOne",
      "cookies.policy.useTwo",
      "cookies.policy.useThree",
      "cookies.policy.useFour"
    ];

    items.forEach(function (
      item,
      index
    ) {
      if (itemKeys[index]) {
        item.setAttribute(
          "data-i18n",
          itemKeys[index]
        );
      }
    });
  }

  function translateContact() {
    const dictionary =
      getDictionary();

    const paragraphs =
      document.querySelectorAll(
        ".policy > p"
      );

    const contactParagraph =
      paragraphs[5];

    if (contactParagraph) {
      contactParagraph.innerHTML =
        dictionary.policy.contactText +
        "<br><br>" +
        '<a href="mailto:petsanddogue@gmail.com">' +
        "petsanddogue@gmail.com" +
        "</a>";
    }
  }

  function prepareFooter() {
    setText(
      "footer > p",
      "common.footer.subtitle"
    );

    setMany(
      ".footer-links a",
      [
        "cookies.footer.privacy",
        "cookies.footer.terms",
        "cookies.footer.copyright",
        "cookies.footer.cookies",
        "cookies.footer.contact",
        "cookies.footer.advertise"
      ]
    );

    setText(
      ".admin-small",
      "cookies.footer.admin"
    );
  }

  function updateMetadata() {
    document.title =
      getDictionary().meta.title;

    document.documentElement.lang =
      getLanguageCode();
  }

  function preparePage() {
    prepareNavigation();
    preparePolicy();
    prepareFooter();
    translateContact();
    updateMetadata();
  }

  window.addEventListener(
    "petsdogue:languagechange",
    function () {
      window.setTimeout(
        function () {
          translateContact();
          updateMetadata();
        },
        0
      );
    }
  );

  if (
    document.readyState === "loading"
  ) {
    document.addEventListener(
      "DOMContentLoaded",
      preparePage,
      {
        once: true
      }
    );
  } else {
    preparePage();
  }
})();
