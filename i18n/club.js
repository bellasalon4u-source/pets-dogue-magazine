(function () {
  "use strict";

  function setText(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n",
        key
      );
    }
  }

  function setMany(selector, keys) {
    document
      .querySelectorAll(selector)
      .forEach((element, index) => {
        if (keys[index]) {
          element.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function getLanguageCode() {
    if (
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage
        .getCurrentLanguage ===
        "function"
    ) {
      return window.PetsDogueLanguage
        .getCurrentLanguage().code;
    }

    return (
      new URLSearchParams(
        window.location.search
      ).get("lang") ||
      localStorage.getItem(
        "pets_dogue_language"
      ) ||
      "en"
    );
  }

  function getDictionary() {
    const language =
      getLanguageCode();

    return (
      window.PetsDogueTranslations.club[
        language
      ] ||
      window.PetsDogueTranslations.club.en
    );
  }

  function prepareHero() {
    setText(
      ".hero h1",
      "club.hero.title"
    );

    setText(
      ".hero p",
      "club.hero.description"
    );

    setMany(
      ".hero-buttons a",
      [
        "club.hero.join",
        "club.hero.competition",
        "club.hero.marketplace"
      ]
    );
  }

  function prepareIntro() {
    setText(
      ".intro h2",
      "club.intro.title"
    );

    setText(
      ".intro p",
      "club.intro.description"
    );
  }

  function preparePricing() {
    setText(
      "#pricing",
      "club.pricing.title"
    );

    const plans =
      document.querySelectorAll(
        ".pricing .plan"
      );

    const planKeys = [
      {
        badge:
          "club.pricing.monthlyBadge",
        title:
          "club.pricing.monthlyTitle",
        description:
          "club.pricing.monthlyDescription",
        items: [
          "club.pricing.monthlyOne",
          "club.pricing.monthlyTwo",
          "club.pricing.monthlyThree",
          "club.pricing.monthlyFour",
          "club.pricing.monthlyFive",
          "club.pricing.monthlySix"
        ],
        join:
          "club.pricing.monthlyJoin"
      },

      {
        badge:
          "club.pricing.yearlyBadge",
        title:
          "club.pricing.yearlyTitle",
        description:
          "club.pricing.yearlyDescription",
        items: [
          "club.pricing.yearlyOne",
          "club.pricing.yearlyTwo",
          "club.pricing.yearlyThree",
          "club.pricing.yearlyFour",
          "club.pricing.yearlyFive",
          "club.pricing.yearlySix",
          "club.pricing.yearlySeven"
        ],
        join:
          "club.pricing.yearlyJoin"
      }
    ];

    plans.forEach((plan, index) => {
      const keys =
        planKeys[index];

      if (!keys) return;

      const badge =
        plan.querySelector(".badge");

      const title =
        plan.querySelector("h3");

      const description =
        plan.querySelector(":scope > p");

      const listItems =
        plan.querySelectorAll("li");

      const buttons =
        plan.querySelectorAll(".btn");

      if (badge) {
        badge.setAttribute(
          "data-i18n",
          keys.badge
        );
      }

      if (title) {
        title.setAttribute(
          "data-i18n",
          keys.title
        );
      }

      if (description) {
        description.setAttribute(
          "data-i18n",
          keys.description
        );
      }

      listItems.forEach(
        (item, itemIndex) => {
          if (keys.items[itemIndex]) {
            item.setAttribute(
              "data-i18n",
              keys.items[itemIndex]
            );
          }
        }
      );

      if (buttons[0]) {
        buttons[0].setAttribute(
          "data-i18n",
          keys.join
        );
      }

      if (buttons[1]) {
        buttons[1].setAttribute(
          "data-i18n",
          "club.pricing.marketplace"
        );
      }
    });
  }

  function prepareBenefits() {
    const titles =
      document.querySelectorAll(
        ".section-title"
      );

    if (titles[1]) {
      titles[1].setAttribute(
        "data-i18n",
        "club.benefits.title"
      );
    }

    const benefitKeys = [
      [
        "club.benefits.coverTitle",
        "club.benefits.coverText"
      ],
      [
        "club.benefits.mediaTitle",
        "club.benefits.mediaText"
      ],
      [
        "club.benefits.storiesTitle",
        "club.benefits.storiesText"
      ],
      [
        "club.benefits.votesTitle",
        "club.benefits.votesText"
      ],
      [
        "club.benefits.marketplaceTitle",
        "club.benefits.marketplaceText"
      ],
      [
        "club.benefits.homeTitle",
        "club.benefits.homeText"
      ],
      [
        "club.benefits.youngTitle",
        "club.benefits.youngText"
      ],
      [
        "club.benefits.breedingTitle",
        "club.benefits.breedingText"
      ],
      [
        "club.benefits.partnerTitle",
        "club.benefits.partnerText"
      ]
    ];

    document
      .querySelectorAll(
        ".benefits .benefit"
      )
      .forEach((benefit, index) => {
        const keys =
          benefitKeys[index];

        if (!keys) return;

        const title =
          benefit.querySelector("h3");

        const text =
          benefit.querySelector("p");

        if (title) {
          title.setAttribute(
            "data-i18n",
            keys[0]
          );
        }

        if (text) {
          text.setAttribute(
            "data-i18n",
            keys[1]
          );
        }
      });
  }

  function prepareCompetition() {
    setText(
      ".cover-competition h2",
      "club.competition.title"
    );

    setText(
      ".cover-competition > p",
      "club.competition.description"
    );

    setMany(
      ".competition-item",
      [
        "club.competition.cover",
        "club.competition.story",
        "club.competition.video",
        "club.competition.visibility",
        "club.competition.finalist",
        "club.competition.voting"
      ]
    );

    setMany(
      ".cover-competition > .btn",
      [
        "club.competition.enter",
        "club.competition.marketplace"
      ]
    );
  }

  function prepareMemberCard() {
    setText(
      ".member-card > h2",
      "club.memberCard.title"
    );

    setText(
      ".member-card > p",
      "club.memberCard.description"
    );

    setText(
      ".card-preview h3",
      "club.memberCard.heading"
    );
  }

  function translateMemberCard() {
    const dictionary =
      getDictionary();

    const paragraphs =
      document.querySelectorAll(
        ".card-preview p"
      );

    if (paragraphs[0]) {
      paragraphs[0].innerHTML =
        `<strong>${dictionary.memberCard.member}</strong> ${dictionary.memberCard.memberValue}`;
    }

    if (paragraphs[1]) {
      paragraphs[1].innerHTML =
        `<strong>${dictionary.memberCard.status}</strong> ${dictionary.memberCard.statusValue}`;
    }

    if (paragraphs[2]) {
      paragraphs[2].innerHTML =
        `<strong>${dictionary.memberCard.access}</strong> ${dictionary.memberCard.accessValue}`;
    }
  }

  function prepareMarketplace() {
    setText(
      ".marketplace h2",
      "club.marketplace.title"
    );

    setText(
      ".marketplace > p",
      "club.marketplace.description"
    );

    setMany(
      ".marketplace-item",
      [
        "club.marketplace.home",
        "club.marketplace.young",
        "club.marketplace.breeding",
        "club.marketplace.accessories",
        "club.marketplace.grooming",
        "club.marketplace.photography",
        "club.marketplace.hotels",
        "club.marketplace.walking"
      ]
    );

    setText(
      ".marketplace > .btn",
      "club.marketplace.button"
    );
  }

  function prepareFooter() {
    setText(
      "footer p",
      "common.footer.subtitle"
    );

    setMany(
      ".footer-links a",
      [
        "club.footer.home",
        "club.footer.gallery",
        "club.footer.marketplace",
        "club.footer.partners",
        "club.footer.contests",
        "club.footer.petsInNeed",
        "club.footer.privacy",
        "club.footer.contact"
      ]
    );

    setText(
      ".admin-small",
      "club.footer.admin"
    );
  }

  function updateTitle() {
    document.title =
      getDictionary().meta.title;
  }

  function preparePage() {
    prepareHero();
    prepareIntro();
    preparePricing();
    prepareBenefits();
    prepareCompetition();
    prepareMemberCard();
    prepareMarketplace();
    prepareFooter();
    translateMemberCard();
    updateTitle();
  }

  window.addEventListener(
    "petsdogue:languagechange",
    function () {
      window.setTimeout(
        function () {
          translateMemberCard();
          updateTitle();
        },
        0
      );
    }
  );

  if (
    document.readyState === "loading"
  ) {
    document.addEventListener(
      "DOMContentLoaded",
      preparePage,
      {
        once: true
      }
    );
  } else {
    preparePage();
  }
})();
