(function () {
  "use strict";

  function setText(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n",
        key
      );
    }
  }

  function setMany(selector, keys) {
    document
      .querySelectorAll(selector)
      .forEach(function (element, index) {
        if (keys[index]) {
          element.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function getLanguageCode() {
    if (
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage
        .getCurrentLanguage === "function"
    ) {
      return window.PetsDogueLanguage
        .getCurrentLanguage().code;
    }

    return (
      new URLSearchParams(
        window.location.search
      ).get("lang") ||
      localStorage.getItem(
        "pets_dogue_language"
      ) ||
      "en"
    );
  }

  function getDictionary() {
    const language =
      getLanguageCode();

    return (
      window.PetsDogueTranslations
        .terms[language] ||
      window.PetsDogueTranslations
        .terms.en
    );
  }

  function prepareNavigation() {
    setMany(
      "header nav a",
      [
        "terms.navigation.home",
        "terms.navigation.latestIssue",
        "terms.navigation.archive",
        "terms.navigation.articles",
        "terms.navigation.categories",
        "terms.navigation.about",
        "terms.navigation.advertise",
        "terms.navigation.contact"
      ]
    );
  }

  function preparePolicy() {
    setText(
      ".policy h1",
      "terms.policy.title"
    );

    const paragraphs =
      document.querySelectorAll(
        ".policy > p"
      );

    const paragraphKeys = [
      "terms.policy.introduction",
      "terms.policy.websiteText",
      "terms.policy.editorialText",
      "terms.policy.advertisingText",
      "terms.policy.submissionsText",
      "terms.policy.propertyText",
      "terms.policy.liabilityText",
      "terms.policy.changesText"
    ];

    paragraphs.forEach(function (
      paragraph,
      index
    ) {
      if (paragraphKeys[index]) {
        paragraph.setAttribute(
          "data-i18n",
          paragraphKeys[index]
        );
      }
    });

    const headings =
      document.querySelectorAll(
        ".policy h2"
      );

    const headingKeys = [
      "terms.policy.websiteTitle",
      "terms.policy.editorialTitle",
      "terms.policy.advertisingTitle",
      "terms.policy.submissionsTitle",
      "terms.policy.propertyTitle",
      "terms.policy.liabilityTitle",
      "terms.policy.changesTitle",
      "terms.policy.contactTitle"
    ];

    headings.forEach(function (
      heading,
      index
    ) {
      if (headingKeys[index]) {
        heading.setAttribute(
          "data-i18n",
          headingKeys[index]
        );
      }
    });
  }

  function translateContact() {
    const dictionary =
      getDictionary();

    const paragraphs =
      document.querySelectorAll(
        ".policy > p"
      );

    const contactParagraph =
      paragraphs[8];

    if (contactParagraph) {
      contactParagraph.innerHTML =
        dictionary.policy.contactText +
        "<br><br>" +
        '<a href="mailto:petsanddogue@gmail.com">' +
        "petsanddogue@gmail.com" +
        "</a>";
    }
  }

  function prepareFooter() {
    setText(
      "footer > p",
      "common.footer.subtitle"
    );

    setMany(
      ".footer-links a",
      [
        "terms.footer.privacy",
        "terms.footer.terms",
        "terms.footer.copyright",
        "terms.footer.cookies",
        "terms.footer.contact",
        "terms.footer.advertise"
      ]
    );

    setText(
      ".admin-small",
      "terms.footer.admin"
    );
  }

  function updateMetadata() {
    document.title =
      getDictionary().meta.title;

    document.documentElement.lang =
      getLanguageCode();
  }

  function preparePage() {
    prepareNavigation();
    preparePolicy();
    prepareFooter();
    translateContact();
    updateMetadata();
  }

  window.addEventListener(
    "petsdogue:languagechange",
    function () {
      window.setTimeout(
        function () {
          translateContact();
          updateMetadata();
        },
        0
      );
    }
  );

  if (
    document.readyState === "loading"
  ) {
    document.addEventListener(
      "DOMContentLoaded",
      preparePage,
      {
        once: true
      }
    );
  } else {
    preparePage();
  }
})();
