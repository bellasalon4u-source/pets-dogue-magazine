(function () {
  "use strict";

  const fallbackTranslationIds = {
    "fallback-miso": "miso",
    "fallback-golden": "golden",
    "fallback-cat": "cat",
    "fallback-bird": "bird",
    "fallback-star": "star",
    "fallback-icon": "icon"
  };

  function setText(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n",
        key
      );
    }
  }

  function setPlaceholder(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n-placeholder",
        key
      );
    }
  }

  function setMany(selector, keys) {
    document
      .querySelectorAll(selector)
      .forEach((element, index) => {
        if (keys[index]) {
          element.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function getLanguageCode() {
    if (
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage
        .getCurrentLanguage === "function"
    ) {
      return window.PetsDogueLanguage
        .getCurrentLanguage().code;
    }

    return "en";
  }

  function getDictionary() {
    const languageCode =
      getLanguageCode();

    return (
      window.PetsDogueTranslations
        .photos[languageCode] ||
      window.PetsDogueTranslations
        .photos.en
    );
  }

  function getPhotoTranslation(photo) {
    const translationName =
      fallbackTranslationIds[
        String(photo.id)
      ];

    if (!translationName) {
      return null;
    }

    const dictionary =
      getDictionary();

    return (
      dictionary.fallback[
        translationName
      ] ||
      null
    );
  }

  function getDisplayPhoto(photo) {
    const translation =
      getPhotoTranslation(photo);

    if (!translation) {
      return {
        title:
          photo.title ||
          getDictionary().gallery
            .untitled,

        category:
          photo.category ||
          "PHOTO",

        photographer:
          photo.photographer ||
          "PETS & DOGUE",

        caption:
          photo.caption ||
          getDictionary().gallery
            .defaultCaption
      };
    }

    return {
      title:
        translation.title,

      category:
        translation.category,

      photographer:
        translation.photographer,

      caption:
        translation.caption
    };
  }

  function prepareStaticPage() {
    setText(
      ".hero-content h1",
      "photos.hero.title"
    );

    setText(
      ".hero-content p",
      "photos.hero.description"
    );

    setText(
      ".section-title",
      "photos.gallery.title"
    );

    setPlaceholder(
      "#photoSearch",
      "photos.gallery.searchPlaceholder"
    );

    setText(
      ".search-panel button",
      "photos.gallery.searchButton"
    );

    setMany(
      "#categorySearch option",
      [
        "photos.gallery.allCategories",
        "photos.gallery.coverPhoto",
        "photos.gallery.editorial",
        "photos.gallery.portrait",
        "photos.gallery.community",
        "photos.gallery.fashion",
        "photos.gallery.travel",
        "photos.gallery.rescue",
        "photos.gallery.exotic"
      ]
    );

    setMany(
      ".category-button",
      [
        "photos.gallery.all",
        "photos.gallery.coverPhotos",
        "photos.gallery.editorial",
        "photos.gallery.portraits",
        "photos.gallery.community",
        "photos.gallery.fashion",
        "photos.gallery.travel",
        "photos.gallery.rescue"
      ]
    );

    setText(
      "#emptyState h3",
      "photos.gallery.emptyTitle"
    );

    setText(
      "#emptyState p",
      "photos.gallery.emptyDescription"
    );

    setText(
      ".feature h2",
      "photos.feature.title"
    );

    setText(
      ".feature p",
      "photos.feature.description"
    );

    setText(
      ".feature a",
      "photos.feature.button"
    );

    setText(
      "footer p",
      "common.footer.subtitle"
    );

    setMany(
      ".footer-links a",
      [
        "photos.footer.home",
        "photos.footer.articles",
        "photos.footer.coverStars",
        "photos.footer.membersGallery",
        "photos.footer.hallOfFame",
        "photos.footer.account",
        "photos.footer.privacy",
        "photos.footer.contact"
      ]
    );

    setText(
      ".admin-small",
      "photos.footer.admin"
    );
  }

  function updatePageTitle() {
    const dictionary =
      getDictionary();

    if (
      dictionary.meta &&
      dictionary.meta.title
    ) {
      document.title =
        dictionary.meta.title;
    }
  }

  const originalCreatePhotoCard =
    window.createPhotoCard;

  if (
    typeof originalCreatePhotoCard ===
    "function"
  ) {
    window.createPhotoCard =
      function (photo) {
        const display =
          getDisplayPhoto(photo);

        const id =
          String(photo.id);

        const initialLikes =
          photoLikes[id] !== undefined
            ? photoLikes[id]
            : Number(
                photo.likes || 0
              );

        const liked =
          Boolean(likedPhotos[id]);

        const image =
          photo.image ||
          "https://images.unsplash.com/photo-1450778869180-41d0601e046e?auto=format&fit=crop&w=1200&q=80";

        const dictionary =
          getDictionary();

        return `
<article class="photo-card">

<div
class="photo-image"
onclick="openLightbox('${escapeHTML(id)}')">

<img
src="${image}"
alt="${escapeHTML(display.title)}">

<span class="zoom-label">
${escapeHTML(dictionary.gallery.viewPhoto)}
</span>

</div>

<div class="photo-content">

<span class="badge">
${escapeHTML(display.category)}
</span>

<h3>
${escapeHTML(display.title)}
</h3>

<p>
${escapeHTML(display.caption)}
</p>

<div class="meta">

<span>
📸 ${escapeHTML(display.photographer)}
</span>

<button
class="heart ${liked ? "liked" : ""}"
onclick="likePhoto('${escapeHTML(id)}',this)">
❤️ <span>${initialLikes}</span>
</button>

</div>

</div>

</article>
`;
      };
  }

  const originalOpenLightbox =
    window.openLightbox;

  if (
    typeof originalOpenLightbox ===
    "function"
  ) {
    window.openLightbox =
      function (id) {
        const photo =
          publicPhotos.find(
            (item) =>
              String(item.id) ===
              String(id)
          );

        if (!photo) {
          return;
        }

        const display =
          getDisplayPhoto(photo);

        const dictionary =
          getDictionary();

        document
          .getElementById(
            "lightboxImage"
          ).src = photo.image;

        document
          .getElementById(
            "lightboxTitle"
          ).textContent =
          display.title ||
          dictionary.gallery
            .defaultPhoto;

        document
          .getElementById(
            "lightboxCategory"
          ).textContent =
          display.category;

        document
          .getElementById(
            "lightboxMeta"
          ).textContent =
          dictionary.gallery
            .photographer +
          ": " +
          display.photographer;

        document
          .getElementById(
            "lightboxCaption"
          ).textContent =
          display.caption;

        document
          .getElementById(
            "lightbox"
          )
          .classList.add("open");

        document.body.style.overflow =
          "hidden";
      };
  }

  function refreshDynamicPhotos() {
    if (
      typeof window.renderPhotos ===
      "function"
    ) {
      window.renderPhotos();
    }
  }

  function preparePage() {
    prepareStaticPage();
    updatePageTitle();
    refreshDynamicPhotos();
  }

  window.addEventListener(
    "petsdogue:languagechange",
    function () {
      window.setTimeout(
        function () {
          updatePageTitle();
          refreshDynamicPhotos();
        },
        0
      );
    }
  );

  if (
    document.readyState === "loading"
  ) {
    document.addEventListener(
      "DOMContentLoaded",
      preparePage,
      { once: true }
    );
  } else {
    preparePage();
  }
})();
