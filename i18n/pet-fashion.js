(function () {
  "use strict";

  function setText(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n",
        key
      );
    }
  }

  function setMany(selector, keys) {
    document
      .querySelectorAll(selector)
      .forEach((element, index) => {
        if (keys[index]) {
          element.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function getCurrentLanguageCode() {
    if (
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage
        .getCurrentLanguage === "function"
    ) {
      return window.PetsDogueLanguage
        .getCurrentLanguage().code;
    }

    return "en";
  }

  function getDictionary() {
    const languageCode =
      getCurrentLanguageCode();

    return (
      window.PetsDogueTranslations
        .petFashion[languageCode] ||
      window.PetsDogueTranslations
        .petFashion.en
    );
  }

  function prepareHero() {
    setText(
      ".hero-content h1",
      "petFashion.hero.title"
    );

    setText(
      ".hero-content p",
      "petFashion.hero.description"
    );
  }

  function prepareHighlights() {
    setText(
      ".section-title",
      "petFashion.highlights.title"
    );

    const cards =
      document.querySelectorAll(
        ".grid .card"
      );

    const cardKeys = [
      {
        badge:
          "petFashion.highlights.autumnBadge",
        title:
          "petFashion.highlights.autumnTitle",
        description:
          "petFashion.highlights.autumnDescription",
        button:
          "petFashion.highlights.autumnButton"
      },

      {
        badge:
          "petFashion.highlights.runwayBadge",
        title:
          "petFashion.highlights.runwayTitle",
        description:
          "petFashion.highlights.runwayDescription",
        button:
          "petFashion.highlights.runwayButton"
      },

      {
        badge:
          "petFashion.highlights.accessoriesBadge",
        title:
          "petFashion.highlights.accessoriesTitle",
        description:
          "petFashion.highlights.accessoriesDescription",
        button:
          "petFashion.highlights.accessoriesButton"
      }
    ];

    cards.forEach((card, index) => {
      const keys =
        cardKeys[index];

      if (!keys) {
        return;
      }

      const badge =
        card.querySelector(".badge");

      const title =
        card.querySelector("h3");

      const description =
        card.querySelector("p");

      const button =
        card.querySelector(".shop-btn");

      if (badge) {
        badge.setAttribute(
          "data-i18n",
          keys.badge
        );
      }

      if (title) {
        title.setAttribute(
          "data-i18n",
          keys.title
        );
      }

      if (description) {
        description.setAttribute(
          "data-i18n",
          keys.description
        );
      }

      if (button) {
        button.setAttribute(
          "data-i18n",
          keys.button
        );
      }
    });
  }

  function prepareShopping() {
    setText(
      ".feature h2",
      "petFashion.shopping.title"
    );

    setText(
      ".feature > p",
      "petFashion.shopping.description"
    );

    setMany(".brands .brand", [
      "petFashion.shopping.apparel",
      "petFashion.shopping.collars",
      "petFashion.shopping.travel",
      "petFashion.shopping.beds",
      "petFashion.shopping.jewellery",
      "petFashion.shopping.discounts"
    ]);
  }

  function prepareFooter() {
    setText(
      "footer p",
      "common.footer.subtitle"
    );

    setMany(".footer-links a", [
      "common.footer.home",
      "common.footer.coverStars",
      "petFashion.footer.hallOfFame",
      "common.footer.privacy",
      "common.footer.terms",
      "common.footer.contact"
    ]);

    setText(
      ".admin-small",
      "common.footer.admin"
    );
  }

  function updatePageTitle() {
    const dictionary =
      getDictionary();

    if (
      dictionary &&
      dictionary.meta &&
      dictionary.meta.title
    ) {
      document.title =
        dictionary.meta.title;
    }
  }

  function preparePage() {
    prepareHero();
    prepareHighlights();
    prepareShopping();
    prepareFooter();
    updatePageTitle();
  }

  window.addEventListener(
    "petsdogue:languagechange",
    function () {
      window.setTimeout(
        updatePageTitle,
        0
      );
    }
  );

  if (
    document.readyState === "loading"
  ) {
    document.addEventListener(
      "DOMContentLoaded",
      preparePage,
      {
        once: true
      }
    );
  } else {
    preparePage();
  }
})();
