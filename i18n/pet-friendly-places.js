  function setText(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n",
        key
      );
    }
  }

  function setPlaceholder(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n-placeholder",
        key
      );
    }
  }

  function setMany(selector, keys) {
    document
      .querySelectorAll(selector)
      .forEach((element, index) => {
        if (keys[index]) {
          element.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function getLanguageCode() {
    if (
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage
        .getCurrentLanguage ===
        "function"
    ) {
      return window.PetsDogueLanguage
        .getCurrentLanguage().code;
    }

    const urlLanguage =
      new URLSearchParams(
        window.location.search
      ).get("lang");

    if (urlLanguage) {
      return urlLanguage;
    }

    return (
      localStorage.getItem(
        "pets_dogue_language"
      ) || "en"
    );
  }

  function getDictionary() {
    const code =
      getLanguageCode();

    return (
      window.PetsDogueTranslations
        .petFriendlyPlaces[code] ||
      window.PetsDogueTranslations
        .petFriendlyPlaces.en
    );
  }

  function translateExactText() {
    const walker =
      document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT
      );

    const nodes = [];

    while (walker.nextNode()) {
      nodes.push(walker.currentNode);
    }

    nodes.forEach((node) => {
      const original =
        node.textContent.trim();

      const key =
        TEXT_KEYS[original];

      if (!key) {
        return;
      }

      const parent =
        node.parentElement;

      if (!parent) {
        return;
      }

      parent.setAttribute(
        "data-i18n",
        key
      );
    });
  }

