(function () {
  "use strict";

  function setText(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n",
        key
      );
    }
  }

  function setMany(selector, keys) {
    document
      .querySelectorAll(selector)
      .forEach(function (element, index) {
        if (keys[index]) {
          element.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function getLanguageCode() {
    if (
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage
        .getCurrentLanguage === "function"
    ) {
      return window.PetsDogueLanguage
        .getCurrentLanguage().code;
    }

    return (
      new URLSearchParams(
        window.location.search
      ).get("lang") ||
      localStorage.getItem(
        "pets_dogue_language"
      ) ||
      "en"
    );
  }

  function getDictionary() {
    const language =
      getLanguageCode();

    return (
      window.PetsDogueTranslations
        .privacy[language] ||
      window.PetsDogueTranslations
        .privacy.en
    );
  }

  function prepareNavigation() {
    setMany(
      "header nav a",
      [
        "privacy.navigation.home",
        "privacy.navigation.latestIssue",
        "privacy.navigation.archive",
        "privacy.navigation.articles",
        "privacy.navigation.categories",
        "privacy.navigation.about",
        "privacy.navigation.advertise",
        "privacy.navigation.contact"
      ]
    );
  }

  function preparePolicy() {
    const policy =
      document.querySelector(".policy");

    if (!policy) return;

    setText(
      ".policy h1",
      "privacy.policy.title"
    );

    const directParagraphs =
      policy.querySelectorAll(
        ":scope > p"
      );

    if (directParagraphs[0]) {
      directParagraphs[0].setAttribute(
        "data-i18n",
        "privacy.policy.introduction"
      );
    }

    if (directParagraphs[1]) {
      directParagraphs[1].setAttribute(
        "data-i18n",
        "privacy.policy.protectionText"
      );
    }

    if (directParagraphs[2]) {
      directParagraphs[2].setAttribute(
        "data-i18n",
        "privacy.policy.cookiesText"
      );
    }

    const headings =
      policy.querySelectorAll("h2");

    const headingKeys = [
      "privacy.policy.collectTitle",
      "privacy.policy.useTitle",
      "privacy.policy.protectionTitle",
      "privacy.policy.cookiesTitle",
      "privacy.policy.contactTitle"
    ];

    headings.forEach(function (
      heading,
      index
    ) {
      if (headingKeys[index]) {
        heading.setAttribute(
          "data-i18n",
          headingKeys[index]
        );
      }
    });

    const lists =
      policy.querySelectorAll("ul");

    if (lists[0]) {
      const items =
        lists[0].querySelectorAll("li");

      const keys = [
        "privacy.policy.collectOne",
        "privacy.policy.collectTwo",
        "privacy.policy.collectThree",
        "privacy.policy.collectFour"
      ];

      items.forEach(function (
        item,
        index
      ) {
        if (keys[index]) {
          item.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
    }

    if (lists[1]) {
      const items =
        lists[1].querySelectorAll("li");

      const keys = [
        "privacy.policy.useOne",
        "privacy.policy.useTwo",
        "privacy.policy.useThree",
        "privacy.policy.useFour"
      ];

      items.forEach(function (
        item,
        index
      ) {
        if (keys[index]) {
          item.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
    }
  }

  function translateContact() {
    const dictionary =
      getDictionary();

    const policy =
      document.querySelector(".policy");

    if (!policy) return;

    const paragraphs =
      policy.querySelectorAll(
        ":scope > p"
      );

    const contactParagraph =
      paragraphs[3];

    if (contactParagraph) {
      contactParagraph.innerHTML =
        dictionary.policy.contactText +
        "<br><br>" +
        '<a href="mailto:petsanddogue@gmail.com">' +
        "petsanddogue@gmail.com" +
        "</a>";
    }
  }

  function prepareFooter() {
    setText(
      "footer > p",
      "common.footer.subtitle"
    );

    setMany(
      ".footer-links a",
      [
        "privacy.footer.privacy",
        "privacy.footer.terms",
        "privacy.footer.copyright",
        "privacy.footer.cookies",
        "privacy.footer.contact",
        "privacy.footer.advertise"
      ]
    );

    setText(
      ".admin-small",
      "privacy.footer.admin"
    );
  }

  function updateMetadata() {
    document.title =
      getDictionary().meta.title;

    document.documentElement.lang =
      getLanguageCode();
  }

  function preparePage() {
    prepareNavigation();
    preparePolicy();
    prepareFooter();
    translateContact();
    updateMetadata();
  }

  window.addEventListener(
    "petsdogue:languagechange",
    function () {
      window.setTimeout(
        function () {
          translateContact();
          updateMetadata();
        },
        0
      );
    }
  );

  if (
    document.readyState === "loading"
  ) {
    document.addEventListener(
      "DOMContentLoaded",
      preparePage,
      {
        once: true
      }
    );
  } else {
    preparePage();
  }
})();
