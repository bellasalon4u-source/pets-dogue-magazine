  function replaceDynamicText() {
    const dictionary =
      getDictionary();

    document.title =
      dictionary.meta.title;

    document
      .querySelectorAll(
        "#contestGrid .badge"
      )
      .forEach((element) => {
        if (
          element.textContent
            .trim() ===
          "PETS & DOGUE CONTEST"
        ) {
          element.textContent =
            dictionary.dynamic
              .contestBadge;
        }
      });

    document
      .querySelectorAll(
        "#contestGrid .status-label"
      )
      .forEach((element) => {
        const status =
          element.textContent.trim();

        const translations = {
          Open:
            dictionary.dynamic.open,

          Draft:
            dictionary.dynamic.draft,

          "Voting Closed":
            dictionary.dynamic
              .votingClosed,

          Completed:
            dictionary.dynamic.completed
        };

        if (translations[status]) {
          element.textContent =
            translations[status];
        }
      });

    document
      .querySelectorAll(
        "#contestGrid .actions .btn"
      )
      .forEach((element) => {
        const text =
          element.textContent.trim();

        if (text === "Join Now") {
          element.textContent =
            dictionary.dynamic.joinNow;
        }

        if (
          text === "View Details"
        ) {
          element.textContent =
            dictionary.dynamic
              .viewDetails;
        }
      });

    document
      .querySelectorAll(
        "#contestGrid .vote"
      )
      .forEach((element) => {
        const number =
          element.querySelector("span");

        if (!number) {
          return;
        }

        element.innerHTML =
          `❤️ <span>${number.textContent}</span> ${dictionary.dynamic.votes}`;
      });

    document
      .querySelectorAll(
        "#contestGrid .prize-line"
      )
      .forEach((element) => {
        element.childNodes
          .forEach((node) => {
            if (
              node.nodeType ===
              Node.TEXT_NODE
            ) {
              node.textContent =
                node.textContent.replace(
                  "🎁 Prize:",
                  dictionary.dynamic.prize
                );
            }
          });
      });

    const modalStatus =
      document.getElementById(
        "modalStatus"
      );

    if (modalStatus) {
      const statuses = {
        Open:
          dictionary.dynamic.open,

        Draft:
          dictionary.dynamic.draft,

        "Voting Closed":
          dictionary.dynamic
            .votingClosed,

        Completed:
          dictionary.dynamic.completed
      };

      const current =
        modalStatus.textContent.trim();

      if (statuses[current]) {
        modalStatus.textContent =
          statuses[current];
      }
    }

    const modalPrize =
      document.getElementById(
        "modalPrize"
      );

    if (
      modalPrize &&
      modalPrize.textContent
        .trim()
        .startsWith("Prize:")
    ) {
      modalPrize.textContent =
        modalPrize.textContent.replace(
          "Prize:",
          dictionary.dynamic.modalPrize
        );
    }

    const modalWinner =
      document.getElementById(
        "modalWinner"
      );

    if (
      modalWinner &&
      modalWinner.textContent
        .trim()
        .startsWith("Winner:")
    ) {
      modalWinner.textContent =
        modalWinner.textContent.replace(
          "Winner:",
          dictionary.dynamic
            .modalWinner
        );
    }
  }

  let observerTimer;

  function scheduleTranslation() {
    window.clearTimeout(
      observerTimer
    );

    observerTimer =
      window.setTimeout(
        replaceDynamicText,
        40
      );
  }

  function preparePage() {
    prepareStaticPage();
    replaceDynamicText();

    const observer =
      new MutationObserver(
        scheduleTranslation
      );

    observer.observe(
      document.body,
      {
        childList: true,
        subtree: true,
        characterData: true
      }
    );
  }

  window.addEventListener(
    "petsdogue:languagechange",
    function () {
      window.setTimeout(
        replaceDynamicText,
        0
      );
    }
  );

  if (
    document.readyState ===
    "loading"
  ) {
    document.addEventListener(
      "DOMContentLoaded",
      preparePage,
      {
        once: true
      }
    );
  } else {
    preparePage();
  }
