(function () {
  "use strict";

  function setText(selector, key) {
    const element =
      document.querySelector(selector);

    if (element) {
      element.setAttribute(
        "data-i18n",
        key
      );
    }
  }

  function setMany(selector, keys) {
    document
      .querySelectorAll(selector)
      .forEach((element, index) => {
        if (keys[index]) {
          element.setAttribute(
            "data-i18n",
            keys[index]
          );
        }
      });
  }

  function getLanguageCode() {
    if (
      window.PetsDogueLanguage &&
      typeof window.PetsDogueLanguage
        .getCurrentLanguage ===
        "function"
    ) {
      return window.PetsDogueLanguage
        .getCurrentLanguage().code;
    }

    const queryLanguage =
      new URLSearchParams(
        window.location.search
      ).get("lang");

    if (queryLanguage) {
      return queryLanguage;
    }

    return (
      localStorage.getItem(
        "pets_dogue_language"
      ) || "en"
    );
  }

  function getDictionary() {
    const language =
      getLanguageCode();

    return (
      window.PetsDogueTranslations
        .petsInNeed[language] ||
      window.PetsDogueTranslations
        .petsInNeed.en
    );
  }

  function prepareHero() {
    setText(
      ".hero h1",
      "petsInNeed.hero.title"
    );

    setText(
      ".hero p",
      "petsInNeed.hero.description"
    );
  }

  function prepareCards() {
    setText(
      ".section-title",
      "petsInNeed.section.title"
    );

    const cards =
      document.querySelectorAll(
        ".grid .card"
      );

    const cardKeys = [
      {
        badge:
          "petsInNeed.cards.bellaBadge",
        meta:
          "petsInNeed.cards.bellaMeta",
        description:
          "petsInNeed.cards.bellaDescription",
        primary:
          "petsInNeed.cards.bellaPrimary",
        secondary:
          "petsInNeed.cards.bellaSecondary"
      },

      {
        badge:
          "petsInNeed.cards.lunaBadge",
        meta:
          "petsInNeed.cards.lunaMeta",
        description:
          "petsInNeed.cards.lunaDescription",
        primary:
          "petsInNeed.cards.lunaPrimary",
        secondary:
          "petsInNeed.cards.lunaSecondary"
      },

      {
        badge:
          "petsInNeed.cards.shelterBadge",
        title:
          "petsInNeed.cards.shelterTitle",
        meta:
          "petsInNeed.cards.shelterMeta",
        description:
          "petsInNeed.cards.shelterDescription",
        primary:
          "petsInNeed.cards.shelterPrimary",
        secondary:
          "petsInNeed.cards.shelterSecondary"
      }
    ];

    cards.forEach((card, index) => {
      const keys =
        cardKeys[index];

      if (!keys) {
        return;
      }

      const badge =
        card.querySelector(".badge");

      const title =
        card.querySelector("h3");

      const meta =
        card.querySelector(".meta");

      const description =
        card.querySelector(
          ".card-content > p"
        );

      const actions =
        card.querySelectorAll(
          ".actions a"
        );

      if (badge) {
        badge.setAttribute(
          "data-i18n",
          keys.badge
        );
      }

      if (title && keys.title) {
        title.setAttribute(
          "data-i18n",
          keys.title
        );
      }

      if (meta) {
        meta.setAttribute(
          "data-i18n",
          keys.meta
        );
      }

      if (description) {
        description.setAttribute(
          "data-i18n",
          keys.description
        );
      }

      if (actions[0]) {
        actions[0].setAttribute(
          "data-i18n",
          keys.primary
        );
      }

      if (actions[1]) {
        actions[1].setAttribute(
          "data-i18n",
          keys.secondary
        );
      }
    });
  }

  function prepareImpact() {
    setText(
      ".impact h2",
      "petsInNeed.impact.title"
    );

    setText(
      ".impact > p",
      "petsInNeed.impact.description"
    );

    setMany(
      ".impact .stat p",
      [
        "petsInNeed.impact.animals",
        "petsInNeed.impact.volunteers",
        "petsInNeed.impact.stories"
      ]
    );
  }

  function prepareFooter() {
    setText(
      "footer p",
      "common.footer.subtitle"
    );

    setMany(
      ".footer-links a",
      [
        "petsInNeed.footer.home",
        "petsInNeed.footer.community",
        "petsInNeed.footer.volunteer",
        "petsInNeed.footer.privacy",
        "petsInNeed.footer.terms",
        "petsInNeed.footer.contact"
      ]
    );

    setText(
      ".admin-small",
      "petsInNeed.footer.admin"
    );
  }

  function updateTitle() {
    document.title =
      getDictionary().meta.title;
  }

  function preparePage() {
    prepareHero();
    prepareCards();
    prepareImpact();
    prepareFooter();
    updateTitle();
  }

  window.addEventListener(
    "petsdogue:languagechange",
    function () {
      window.setTimeout(
        updateTitle,
        0
      );
    }
  );

  if (
    document.readyState === "loading"
  ) {
    document.addEventListener(
      "DOMContentLoaded",
      preparePage,
      {
        once: true
      }
    );
  } else {
    preparePage();
  }
})();
